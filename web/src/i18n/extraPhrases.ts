export function translateDynamicPhrase(source: string, locale: 'en-US' | 'ja-JP'): string | undefined {
  const rules = locale === 'ja-JP' ? jaDynamicRules : enDynamicRules
  for (const [pattern, replacement] of rules) {
    if (pattern.test(source)) return source.replace(pattern, replacement)
  }
  return undefined
}
