/** 翻译工作流动态组合串（如「运行中 45% · 当前：人声分离」）。 */
export function translateWorkflowDynamic(
  source: string,
  locale: 'en-US' | 'ja-JP',
): string | undefined {
  const rules = locale === 'ja-JP' ? workflowJaRules : workflowEnRules
  for (const [pattern, replacement] of rules) {
    if (pattern.test(source)) return source.replace(pattern, replacement)
  }
  return undefined
}
